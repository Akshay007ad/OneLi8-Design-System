/**
 * Ships the system's knowledge inside @oneli8/react.
 *
 * A consumer's agent that only sees components will invent whatever is missing.
 * So the package carries the design language, the atomic rules, the icon system
 * and an honest inventory: what exists, and how to build what does not without
 * leaving OneLi8. The inventory is derived from the source tree rather than
 * written by hand, so it cannot describe a component that is not there.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, cpSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const PKG = join(ROOT, 'packages/react');
const ctx = JSON.parse(readFileSync(join(ROOT, 'ai-context.json'), 'utf8'));
const version = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version;

// --- inventory, read from the tree rather than declared -------------------
const TIER_DIR = { atoms: 'atom', molecules: 'molecule', organisms: 'organism' };
// Only what index.js actually re-exports. An internal helper listed here would
// tell a consumer's agent that a private thing is part of the API.
const publicNames = new Set(
  [...readFileSync(join(PKG, 'src/index.js'), 'utf8').matchAll(/export\s*\{([^}]+)\}/g)]
    .flatMap(m => m[1].split(',').map(n => n.trim().split(/\s+as\s+/).pop().trim()))
    .filter(Boolean)
);
const components = [];
for (const [dir, tier] of Object.entries(TIER_DIR)) {
  const full = join(PKG, 'src', dir);
  if (!existsSync(full)) continue;
  for (const file of readdirSync(full).filter(f => f.endsWith('.js'))) {
    const source = readFileSync(join(full, file), 'utf8');
    const exported = [...source.matchAll(/export (?:const|function) (\w+)/g)]
      .map(m => m[1]).filter(n => publicNames.has(n));
    if (exported.length === 0) continue;
    components.push({
      tier,
      module: `${dir}/${file}`,
      exports: exported,
      // the rule a reviewer would check this against
      constraint: tier === 'atom'
        ? 'Composes no other component. Native elements only.'
        : tier === 'molecule'
          ? 'Composed of atoms. Reusable and more specialised.'
          : 'Composed of atoms, molecules or organisms. May hold application state.',
    });
  }
}

const context = {
  $comment: 'GENERATED by packages/sync/src/build-react-context.mjs — do not edit.',
  system: 'OneLi8',
  version,
  meaning: 'OneLi8 means One Light.',
  readFirst: ['PRINCIPLES.md', 'AGENTS.md', 'skills/'],
  foundations: {
    package: '@oneli8/tokens',
    css: '@oneli8/tokens/css',
    tokenPrefix: '--ol8-',
    namingAuthority: 'Figma. Every variable carries an explicit codeSyntax; names are recorded, not derived.',
    rules: ctx.foundations.rules,
  },
  architecture: { convention: ctx.architecture.convention, rules: ctx.architecture.rules },
  components,
  buildingWhatIsNotHere: {
    principle: 'A component OneLi8 does not ship is still a OneLi8 component. Compose it from these foundations rather than inventing a parallel system.',
    steps: [
      'Check this inventory first. Do not rebuild something that exists.',
      'Pick the tier by what it composes, not by how complex it feels.',
      'Reach for a SEMANTIC token, never a primitive and never a literal value. color-actionprimary-default, not color-blue-600 and not #2c438b.',
      'Every dimension sits on the 3px grid. An exception needs an approval record, not a rounded number.',
      'Icons come from the pool. To draw a new one, follow skills/oneli8-icons: a 24px neutral source on the shared 1.8 stroke, never a per-size stroke.',
      'Give margins to the parent, never to the component.',
      'States are not classes. Use :hover, :active, :focus-visible, [disabled] and data attributes.',
      'Colour is currentColor on icons; the parent supplies the semantic role.',
    ],
    forbidden: [
      'A literal colour, size or font value anywhere in a component.',
      'A primitive token in a component. Primitives are hidden from Figma pickers for the same reason.',
      'An invented icon name. Choose from OL8_ICONS.',
      'A per-size icon stroke. The 1.8 stroke is shared and the 18px master is an exact 0.75 scale of the 24px one.',
      'An outline treatment for a filled selection state, or the reverse. Checkbox and Radio share one language.',
    ],
  },
  materials: {
    gem: {
      strategy: 'attribute',
      emitAs: ctx.materials.gem.emitAs,
      note: ctx.materials.gem.note,
      appliesTo: ctx.materials.gem.appliesTo,
    },
  },
  pending: ctx.pending ?? {},
};

writeFileSync(join(PKG, 'ai-context.json'), JSON.stringify(context, null, 2) + '\n');

// the design language and the skills travel with the install
for (const file of ['PRINCIPLES.md', 'AGENTS.md']) cpSync(join(ROOT, file), join(PKG, file));
mkdirSync(join(PKG, 'skills'), { recursive: true });
cpSync(join(ROOT, 'skills'), join(PKG, 'skills'), { recursive: true });

const tiers = components.reduce((acc, c) => ({ ...acc, [c.tier]: (acc[c.tier] ?? 0) + 1 }), {});
console.log(`✓ react context: ${components.length} components (${Object.entries(tiers).map(([t, n]) => `${n} ${t}`).join(', ')}), principles and ${readdirSync(join(PKG, 'skills')).length} skills bundled`);
