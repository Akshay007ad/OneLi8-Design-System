/**
 * Compiles the adapter surfaces that sit alongside dist/tokens.{css,js,d.ts}:
 *
 *   dist/tailwind/preset.mjs   Tailwind v3 preset
 *   dist/tailwind/theme.css    Tailwind v4 @theme bridge
 *   dist/figma/variables.json  round-trip payload, including the theme modes
 *   dist/status/components.json component maturity, derived from ai-context.json
 *
 * Every adapter emits var(--ol8-*) references rather than resolved values, so a
 * consumer's Tailwind classes follow data-ol8-color-scheme and data-ol8-primary
 * exactly like the raw custom properties do.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const src = JSON.parse(readFileSync(join(ROOT, 'packages/tokens/src/tokens.json'), 'utf8'));
const ctx = JSON.parse(readFileSync(join(ROOT, 'ai-context.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(ROOT, 'packages/tokens/package.json'), 'utf8'));
const out = (p) => join(ROOT, 'packages/tokens/dist', p);

const SKIP_TOP = new Set(['source', 'typography', 'themes']);
const flat = {};
(function walk(node, path) {
  if (node && typeof node === 'object' && 'value' in node) {
    flat[path.join('-')] = node.fallback ? `"${node.value}", ${node.fallback}` : node.value;
    return;
  }
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (path.length === 0 && SKIP_TOP.has(k)) continue;
    if (v && typeof v === 'object') walk(v, [...path, k]);
  }
})(src, []);

const ref = (k) => `var(--ol8-${k})`;
const strip = (k, p) => k.slice(p.length);

// ---- Tailwind ---------------------------------------------------------------
const group = (prefix) => Object.keys(flat).filter(k => k.startsWith(prefix));
const asMap = (keys, prefix) => Object.fromEntries(keys.map(k => [strip(k, prefix), ref(k)]));

const colors = {
  ...asMap(group('color-'), 'color-'),
  ...Object.fromEntries(group('material-').map(k => [strip(k, 'material-'), ref(k)])),
};
const spacing = {
  ...asMap(group('dimension-scale-'), 'dimension-scale-'),
  ...asMap(group('spacing-'), 'spacing-'),
  ...asMap(group('size-icon-'), 'size-icon-'),
};
const preset = {
  theme: {
    extend: {
      colors: { ol8: colors },
      spacing: Object.fromEntries(Object.entries(spacing).map(([k, v]) => [`ol8-${k}`, v])),
      borderRadius: Object.fromEntries(group('shape-radius-').map(k => [`ol8-${strip(k, 'shape-radius-')}`, ref(k)])),
      fontFamily: Object.fromEntries(group('font-family-').map(k => [`ol8-${strip(k, 'font-family-')}`, ref(k)])),
      fontSize: Object.fromEntries(group('font-size-').map(k => [`ol8-${strip(k, 'font-size-')}`, ref(k)])),
      lineHeight: Object.fromEntries(group('font-line-').map(k => [`ol8-${strip(k, 'font-line-')}`, ref(k)])),
      fontWeight: Object.fromEntries(group('font-weight-').map(k => [`ol8-${strip(k, 'font-weight-')}`, ref(k)])),
      boxShadow: Object.fromEntries(group('elevation-').map(k => [`ol8-${strip(k, 'elevation-')}`, ref(k)])),
      borderWidth: Object.fromEntries(group('border-width-').map(k => [`ol8-${strip(k, 'border-width-')}`, ref(k)])),
    },
  },
};
mkdirSync(out('tailwind'), { recursive: true });
writeFileSync(out('tailwind/preset.mjs'),
  `// GENERATED by @oneli8/tokens — do not edit.\nexport default ${JSON.stringify(preset, null, 2)};\n`);

const themeLines = [
  ...Object.entries(colors).map(([k, v]) => `  --color-ol8-${k}: ${v};`),
  ...Object.entries(spacing).map(([k, v]) => `  --spacing-ol8-${k}: ${v};`),
  ...group('shape-radius-').map(k => `  --radius-ol8-${strip(k, 'shape-radius-')}: ${ref(k)};`),
  ...group('font-family-').map(k => `  --font-ol8-${strip(k, 'font-family-')}: ${ref(k)};`),
  ...group('font-size-').map(k => `  --text-ol8-${strip(k, 'font-size-')}: ${ref(k)};`),
  ...group('font-weight-').map(k => `  --font-weight-ol8-${strip(k, 'font-weight-')}: ${ref(k)};`),
  ...group('elevation-').map(k => `  --shadow-ol8-${strip(k, 'elevation-')}: ${ref(k)};`),
];
writeFileSync(out('tailwind/theme.css'),
  `/* GENERATED Tailwind v4 theme bridge — do not edit. */\n@theme {\n${themeLines.join('\n')}\n}\n`);

// ---- Figma round-trip -------------------------------------------------------
const PRIMITIVE = /^color-(blue|cyan|green|yellow|orange|pink|violet|red|neutral|primary)-\d{3}$/;
const titled = (k) => k.split('-').filter(Boolean).map(s => s[0].toUpperCase() + s.slice(1)).join(' / ');
const entry = (k, value, reference = null) => ({ path: k.replace(/-/g, '.'), name: titled(k), variable: `--ol8-${k}`, value, reference });
const collections = { primitive: [], semantic: [], component: [] };
for (const [k, v] of Object.entries(flat)) {
  const bucket = PRIMITIVE.test(k) ? 'primitive' : k.startsWith('component-') ? 'component' : 'semantic';
  collections[bucket].push(entry(k, v));
}
const modes = {};
for (const [axisName, axis] of Object.entries(src.themes ?? {})) {
  if (axisName.startsWith('$')) continue;
  modes[axisName] = {};
  for (const [mode, def] of Object.entries(axis)) {
    if (!def?.overrides) continue;
    modes[axisName][mode] = Object.entries(def.overrides).map(([k, v]) => {
      const m = String(v).match(/^\{(.+)\}$/);
      return entry(k, m ? flat[m[1]] : v, m ? m[1].replace(/-/g, '.') : null);
    });
  }
}
mkdirSync(out('figma'), { recursive: true });
writeFileSync(out('figma/variables.json'), JSON.stringify({
  generated: true,
  source: '@oneli8/tokens',
  version: pkg.version,
  figma: ctx.figma,
  modeAxes: { colorScheme: ['light', 'dark'], primaryFamily: ['blue', 'orange', 'green'] },
  collections,
  modes,
  typographyStyles: Object.entries(src.typography).filter(([r]) => !r.startsWith('$'))
    .map(([role, spec]) => ({ role, class: `.ol8-type-${role}`, ...spec })),
  elevationStyles: Object.entries(src.elevation).filter(([r]) => !r.startsWith('$'))
    .map(([name, def]) => ({ name, variable: `--ol8-elevation-${name}`, value: def.value })),
}, null, 2) + '\n');

// ---- Component status -------------------------------------------------------
// Derived from ai-context.json so it states what this tree actually ships,
// rather than repeating an older release's claims.
const tierOf = (c) => c.tier ?? (c.code?.entry?.includes('/atoms/') ? 'atom'
  : c.code?.entry?.includes('/organisms/') ? 'organism' : 'molecule');
const components = Object.entries(ctx.components).map(([baseClass, c]) => ({
  name: baseClass,
  tier: tierOf(c),
  status: 'Candidate',
  designerApproved: true,
  implementationCertified: false,
  package: c.code?.package ?? '@oneli8/core',
  implementationPath: c.code?.entry ?? null,
  stylesPath: c.code?.styles ?? null,
  figmaNodes: c.figma?.sets ? Object.values(c.figma.sets) : (c.figma?.section ? [c.figma.section] : []),
  knownEvidence: c.verification ? Object.keys(c.verification) : [],
}));
mkdirSync(out('status'), { recursive: true });
writeFileSync(out('status/components.json'), JSON.stringify({
  version: pkg.version,
  generated: true,
  note: 'Status records describe development maturity, not public-beta certification.',
  pending: ctx.pending ?? {},
  components,
}, null, 2) + '\n');

console.log(`✓ adapters -> tailwind/{preset.mjs,theme.css}, figma/variables.json (${collections.primitive.length}+${collections.semantic.length}+${collections.component.length} vars, ${Object.keys(modes).length} mode axes), status/components.json (${components.length} components)`);
